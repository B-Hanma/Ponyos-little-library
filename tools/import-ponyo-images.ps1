<#
  import-ponyo-images.ps1 -- index the pictures in assets/ponyo.

  A web page cannot list a directory, so this writes the index the app
  reads: assets/ponyo/manifest.json.

  Run it after adding or removing pictures:

      powershell -ExecutionPolicy Bypass -File tools/import-ponyo-images.ps1

  It reads the real pixel dimensions out of each file, so the app knows
  each picture's aspect ratio without downloading it first and can hold
  the right amount of space while it loads.

  SLOTS
    A filename containing "home", "dna", "study" or "gallery" is pinned
    to that slot. Anything else is eligible everywhere, which is the
    right default -- most people will drop in eight pictures and never
    think about slots at all.

  FOCAL POINT
    Defaults to 50% across, 38% down: in a portrait-orientation photo of
    a person that is usually the face. Override per picture by editing
    manifest.json afterwards; this script preserves any focal point it
    finds already recorded for a file it recognises.
#>
param(
  [string]$Folder = 'assets/ponyo'
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $root $Folder
if (-not (Test-Path $dir)) {
  Write-Host "No such folder: $dir" -ForegroundColor Red
  exit 1
}
$manifestPath = Join-Path $dir 'manifest.json'

# Keep any focal points that were hand-tuned after a previous run.
$previous = @{}
if (Test-Path $manifestPath) {
  try {
    $old = Get-Content $manifestPath -Raw | ConvertFrom-Json
    foreach ($entry in $old.images) { $previous[$entry.file] = $entry }
  } catch { }
}

$exts = '.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif'
$files = Get-ChildItem -Path $dir -File |
  Where-Object { $exts -contains $_.Extension.ToLower() } |
  Sort-Object Name

$images = @()
foreach ($file in $files) {
  $w = 0; $h = 0
  try {
    $bitmap = [System.Drawing.Image]::FromFile($file.FullName)
    $w = $bitmap.Width; $h = $bitmap.Height
    $bitmap.Dispose()
  } catch {
    # .webp and .avif are not decodable by System.Drawing on every
    # Windows build. That is fine: the app treats ratio 0 as "unknown"
    # and lets the browser decide. Do not drop the picture over it.
    Write-Host "  (could not read dimensions of $($file.Name); using unknown)" -ForegroundColor DarkYellow
  }

  $prior = $previous[$file.Name]
  $focal = if ($prior -and $prior.focal) { $prior.focal } else { @(0.5, 0.38) }
  $alt = if ($prior -and $prior.alt) { $prior.alt } else { 'A picture of Ponyo' }

  $images += [ordered]@{
    file  = $file.Name
    w     = $w
    h     = $h
    focal = $focal
    alt   = $alt
  }
}

$manifest = [ordered]@{
  version = 1
  note    = 'Generated by tools/import-ponyo-images.ps1. Edit focal/alt by hand if you like; a re-run keeps them.'
  images  = $images
}

# -Depth matters: without it the nested focal array is serialised as a
# type name instead of numbers.
$json = $manifest | ConvertTo-Json -Depth 6
[System.IO.File]::WriteAllText($manifestPath, $json, [System.Text.UTF8Encoding]::new($false))

Write-Host ""
if ($images.Count -eq 0) {
  Write-Host "  assets/ponyo is empty -- the app will draw empty frames." -ForegroundColor DarkYellow
  Write-Host "  Copy her pictures in there and run this again." -ForegroundColor DarkYellow
} else {
  Write-Host "  $($images.Count) picture(s) indexed:" -ForegroundColor Green
  foreach ($i in $images) {
    $size = if ($i.w) { "$($i.w)x$($i.h)" } else { 'size unknown' }
    Write-Host ("    {0,-38} {1}" -f $i.file, $size)
  }
}
Write-Host ""
Write-Host "  wrote $manifestPath"
