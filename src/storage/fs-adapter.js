/**
 * fs-adapter.js — a StorageAdapter backed by real files on disk.
 *
 * Same thirteen methods as the IndexedDB adapter, same record shapes,
 * same promises. The repository cannot tell the difference, which is the
 * entire point of `adapter.js` existing.
 *
 * ── THE LAYOUT ────────────────────────────────────────────────────
 *
 *   <root>/
 *     library.json      books, settings, covers, and file METADATA
 *     files/
 *       fl_abc123.jpg   the bytes of one upload
 *     migration.json    written by migrate.js, not by this file
 *
 * One document rather than one file per book. Two hundred books is
 * about 200 KB; rewriting that is a millisecond on any disk made this
 * decade, and a single document can be replaced atomically, which two
 * hundred files cannot. The alternative — a file per record — buys
 * nothing and makes a half-written library possible.
 *
 * Blob BYTES live outside it, because a cover is a megabyte and has no
 * business being re-serialised every time she rates something.
 *
 * ── WHY THE FILESYSTEM ARRIVES AS AN ARGUMENT ─────────────────────
 * `createFsAdapter` is handed a backend rather than importing one. In
 * the desktop app that backend is Tauri's fs plugin, wired up in
 * platform.js — the only module in the project allowed to know Tauri
 * exists. In the test harness it is a fake that can be told to fail
 * mid-write, which is the only way to prove the atomic-write path does
 * what it claims. This mirrors `createIndexedDbAdapter({ database })`:
 * an argument that exists so the production code itself can be tested,
 * rather than a stand-in for it.
 *
 * ── TWO RULES THAT MATTER MORE THAN THE REST ──────────────────────
 *
 * 1. EVERY WRITE IS SERIALISED. The repository fires writes without
 *    awaiting them ("persist" is deliberately fire-and-forget), so two
 *    edits in the same tick would otherwise both read, both modify and
 *    both write a whole-document snapshot — and the slower one would
 *    land last and erase the other. IndexedDB gets this for free from
 *    transactions. A filesystem does not.
 *
 * 2. NO READER EVER SEES A PARTIAL library.json. Writes go to a temp
 *    file and are renamed over the target, so the file is either the
 *    old document or the new one. A crash during the write leaves a
 *    stray `.tmp` and an intact library.
 */

import { COLLECTIONS, StorageUnavailableError } from './adapter.js';

/** The document version, so a future change has something to switch on. */
export const FS_SCHEMA = 1;

export const LIBRARY_FILE = 'library.json';
export const FILES_DIR = 'files';

/**
 * A sensible extension, so the folder is browsable by hand and a cover
 * she goes looking for opens on a double-click. Nothing reads it back —
 * the real type is in the metadata — so an unknown type is free to be
 * `.bin` rather than a guess.
 */
const EXTENSIONS = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
  'image/gif': '.gif',
  'image/avif': '.avif',
  'application/pdf': '.pdf',
  'text/plain': '.txt',
  'application/epub+zip': '.epub',
};

function extensionFor(type) {
  return EXTENSIONS[String(type || '').toLowerCase()] || '.bin';
}

/**
 * Ids are generated by `newId()` and are already tame, but this is the
 * one place a record id becomes a path, so it is checked rather than
 * trusted. A restored archive is the realistic way a hostile id would
 * arrive.
 */
function safeId(id) {
  const clean = String(id ?? '').replace(/[^A-Za-z0-9._-]/g, '_');
  if (!clean || clean === '.' || clean === '..') {
    throw new Error(`Unusable file id: ${JSON.stringify(id)}`);
  }
  return clean;
}

/**
 * Write, then move into place.
 *
 * The rename is the commit. Until it happens the target file still holds
 * the previous contents, so a failure at any point before it leaves the
 * file exactly as it was. The temp file is cleaned up on the way out of
 * a failure; if even that fails it is left behind, which costs disk
 * space and nothing else.
 *
 * Exported because migrate.js writes the pre-migration archive with the
 * same guarantee — a half-written safety copy would be worse than none.
 */
let tempCounter = 0;
export async function writeFileAtomic(fs, path, data, { text = false } = {}) {
  tempCounter += 1;
  const tmp = `${path}.${tempCounter}.tmp`;
  try {
    if (text) await fs.writeTextFile(tmp, data);
    else await fs.writeFile(tmp, data);
    await fs.rename(tmp, path);
  } catch (error) {
    await fs.remove(tmp).catch(() => {});
    throw error;
  }
}

/** An empty library, in the shape library.json is written in. */
function emptyDocument() {
  return { schema: FS_SCHEMA, updatedAt: '', books: [], settings: [], covers: [], files: [] };
}

/**
 * @param {Object} options
 * @param {Object} options.fs    the filesystem backend (see platform.js)
 * @param {string} [options.root] directory holding library.json
 */
export function createFsAdapter({ fs, root = '' } = {}) {
  if (!fs) throw new Error('createFsAdapter needs a filesystem backend.');

  const join = (...parts) => parts.filter(Boolean).join('/');
  const libraryPath = join(root, LIBRARY_FILE);
  const filesDir = join(root, FILES_DIR);

  /** In-memory mirror of library.json. Reads never touch the disk. */
  let doc = emptyDocument();
  /** @type {Map<string, Object>} keyed collections, built from `doc` */
  const books = new Map();
  const settings = new Map();
  const covers = new Map();
  /** File metadata only — the bytes stay on disk until asked for. */
  const files = new Map();

  let opened = false;

  /* ────────────────────────── the write queue ───────────────────── */

  /**
   * Every disk mutation goes through here, one at a time, in call order.
   *
   * `.then(work, work)` rather than `.then(work)` on purpose: a failed
   * write must not poison the queue behind it. One upload failing is a
   * bad moment; every subsequent save failing silently because the
   * chain rejected once is a lost library.
   */
  let tail = Promise.resolve();
  function enqueue(work) {
    const run = tail.then(work, work);
    tail = run.catch(() => {});
    return run;
  }

  const atomicWrite = (path, data, options) => writeFileAtomic(fs, path, data, options);

  /** Serialise the in-memory document and replace library.json with it. */
  async function flush() {
    doc = {
      schema: FS_SCHEMA,
      updatedAt: new Date().toISOString(),
      books: Array.from(books.values()),
      settings: Array.from(settings.values()),
      covers: Array.from(covers.values()),
      files: Array.from(files.values()),
    };
    await atomicWrite(libraryPath, JSON.stringify(doc), { text: true });
  }

  /**
   * Apply a change to memory, then persist the whole document.
   *
   * Memory is updated before the write rather than after it, which
   * means a failed write leaves memory ahead of the disk. That is
   * deliberate and it matches the layer above: `repository.persist`
   * already sets its own map first and only logs if the save fails.
   * The useful consequence is that the next successful write carries
   * the earlier change with it, so a transient failure heals itself
   * instead of leaving one book permanently unsaved.
   */
  function mutate(change) {
    return enqueue(async () => {
      change();
      await flush();
    });
  }

  const pathFor = (meta) => join(filesDir, `${safeId(meta.id)}${extensionFor(meta.type)}`);

  /** Metadata plus the bytes, in the shape every caller expects. */
  async function hydrate(meta) {
    const bytes = await fs.readFile(pathFor(meta));
    const type = meta.type || 'application/octet-stream';
    return { ...meta, blob: new Blob([bytes], { type }) };
  }

  return {
    name: 'filesystem',
    get root() { return root; },

    /**
     * Read library.json into memory, creating it if this is a fresh
     * library. Everything after this is served from memory.
     */
    async open() {
      if (opened) return;

      try {
        await fs.mkdir(root || '.');
        await fs.mkdir(filesDir);
      } catch (error) {
        throw new StorageUnavailableError('The library folder could not be created.', error);
      }

      let raw = null;
      try {
        if (await fs.exists(libraryPath)) raw = await fs.readTextFile(libraryPath);
      } catch (error) {
        throw new StorageUnavailableError('The library file could not be read.', error);
      }

      if (raw === null) {
        books.clear(); settings.clear(); covers.clear(); files.clear();
        doc = emptyDocument();
        await enqueue(() => flush());
        opened = true;
        return;
      }

      let parsed;
      try {
        parsed = JSON.parse(raw);
      } catch (error) {
        // Refuse rather than start empty. The repository responds to a
        // failed open by running in memory only, and a degraded
        // repository never writes — so the damaged file stays on disk
        // where it can be recovered, instead of being replaced by a
        // blank library the moment she changes anything.
        throw new StorageUnavailableError('The library file is damaged and was not overwritten.', error);
      }
      if (!parsed || typeof parsed !== 'object' || !Array.isArray(parsed.books)) {
        throw new StorageUnavailableError('The library file is not a library.');
      }

      books.clear(); settings.clear(); covers.clear(); files.clear();
      for (const record of parsed.books ?? []) if (record?.id) books.set(record.id, record);
      for (const record of parsed.settings ?? []) if (record?.key) settings.set(record.key, record);
      for (const record of parsed.covers ?? []) if (record?.id) covers.set(record.id, record);
      for (const record of parsed.files ?? []) if (record?.id) files.set(record.id, record);
      doc = parsed;
      opened = true;
    },

    /**
     * Let go of the library. `open()` rebuilds everything from disk, so
     * there is nothing here that needs tearing down.
     *
     * Deliberately does NOT clear the collections. A write queued but
     * not yet run would then serialise the emptied maps and replace
     * library.json with a blank one — turning "I closed it" into "I
     * erased it". Every caller happens to `await flush()` first today,
     * and this makes that a courtesy rather than a requirement.
     */
    close() {
      opened = false;
    },

    /** Resolves once every queued write has finished. */
    async flush() {
      await enqueue(async () => {});
    },

    /* ─────────────────────────── collections ────────────────────── */

    async list(collection) {
      return Array.from(tableFor(collection).values());
    },

    async get(collection, id) {
      return tableFor(collection).get(id);
    },

    async put(collection, record) {
      const table = tableFor(collection);
      const key = record.id ?? record.key;
      await mutate(() => { table.set(key, record); });
      return record;
    },

    async putMany(collection, records) {
      if (!records.length) return records;
      const table = tableFor(collection);
      await mutate(() => {
        for (const record of records) table.set(record.id ?? record.key, record);
      });
      return records;
    },

    async remove(collection, id) {
      const table = tableFor(collection);
      await mutate(() => { table.delete(id); });
    },

    async clear(collection) {
      const table = tableFor(collection);
      await mutate(() => { table.clear(); });
    },

    /* ────────────────────────────── blobs ───────────────────────── */

    /**
     * Bytes first, metadata second.
     *
     * A crash between the two leaves an unreferenced file in `files/`,
     * which is invisible and costs a little disk. The other order would
     * leave a book pointing at bytes that were never written, which is
     * a broken cover she cannot explain or fix.
     */
    async putBlob(record) {
      const meta = {
        id: record.id,
        bookId: record.bookId ?? '',
        name: record.name ?? 'untitled',
        type: record.type || 'application/octet-stream',
        size: record.blob?.size ?? record.size ?? 0,
        role: record.role ?? 'attachment',
        addedAt: record.addedAt ?? new Date().toISOString(),
      };
      const bytes = new Uint8Array(await record.blob.arrayBuffer());

      await enqueue(async () => {
        await atomicWrite(pathFor(meta), bytes);
        files.set(meta.id, meta);
        await flush();
      });
      return record;
    },

    async getBlob(id) {
      const meta = files.get(id);
      if (!meta) return undefined;
      try {
        return await hydrate(meta);
      } catch {
        // Metadata without bytes: the file was removed from under us.
        // An absent blob is the honest answer, and the cover falls back
        // to the drawn one rather than the app throwing mid-render.
        return undefined;
      }
    },

    async removeBlob(id) {
      const meta = files.get(id);
      if (!meta) return;
      await enqueue(async () => {
        await fs.remove(pathFor(meta)).catch(() => {});
        files.delete(id);
        await flush();
      });
    },

    async listBlobsByBook(bookId) {
      const metas = Array.from(files.values()).filter((meta) => meta.bookId === bookId);
      const records = await Promise.all(metas.map((meta) => hydrate(meta).catch(() => null)));
      return records.filter(Boolean);
    },

    async listAllBlobs() {
      const records = await Promise.all(
        Array.from(files.values()).map((meta) => hydrate(meta).catch(() => null)),
      );
      return records.filter(Boolean);
    },

    async clearBlobs() {
      const metas = Array.from(files.values());
      await enqueue(async () => {
        for (const meta of metas) await fs.remove(pathFor(meta)).catch(() => {});
        files.clear();
        await flush();
      });
    },
  };

  function tableFor(collection) {
    if (collection === COLLECTIONS.BOOKS) return books;
    if (collection === COLLECTIONS.SETTINGS) return settings;
    if (collection === COLLECTIONS.COVERS) return covers;
    throw new Error(`Unknown collection: ${collection}`);
  }
}
